def arrow(x1,y1,x2,y2,color=TEAL):
    import math
    C.setStrokeColor(color);C.setFillColor(color);C.setLineWidth(1.3)
    C.line(x1,H-y1,x2,H-y2);a=math.atan2(y2-y1,x2-x1)
    p=C.beginPath();p.moveTo(x2,H-y2)
    for da in (2.65,-2.65):p.lineTo(x2+7*math.cos(a+da),H-(y2+7*math.sin(a+da)))
    p.close();C.drawPath(p,fill=1,stroke=0)


