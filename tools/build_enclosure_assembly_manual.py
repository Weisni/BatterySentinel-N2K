    gx,gy=xy(-8,44)
    C.setStrokeColor(AMBER);C.setLineWidth(3);C.roundRect(gx,H-gy-52*scale,68*scale,52*scale,9,stroke=1,fill=0)
    centers=[(-10,-10),(62,46),(62,-10),(-10,46),(10,-11),(10,47)]
