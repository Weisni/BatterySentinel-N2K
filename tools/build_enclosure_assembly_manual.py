def txt(x,y,s,size=10.5,font='Body',color=INK):
    C.setFillColor(color);C.setFont(font,size);C.drawString(x,H-y-size*.78,s)


def para(x,y,s,width=CW,style='p'):
    p=Paragraph(s,ST[style]);_,h=p.wrap(width,H)
    if y+h>H-46:raise ValueError('Page content overflow: '+s[:90])
    p.drawOn(C,x,H-y-h);AUDIT.append(dict(kind='paragraph',page=C.getPageNumber(),x=x,y=y,w=width,h=h))
    return y+h


def box(x,y,w,h,color=PALE,stroke=False,r=7):
    C.setFillColor(color);C.setStrokeColor(LINE);C.roundRect(x,H-y-h,w,h,r,fill=1,stroke=int(stroke))


def note(y,title,text,warning=False,height=None,x=M,width=CW):
    p=Paragraph(text,ST['p']);_,ph=p.wrap(width-28,H)
    hh=height or ph+47
    box(x,y,width,hh,GOLD if warning else PALE)
    txt(x+14,y+11,title,10.5,'Bold',AMBER if warning else TEAL)
    para(x+14,y+31,text,width-28)
    return y+hh


def table(y,headers,rows,widths):
    data=[[Paragraph(escape(str(s)),ST['head']) for s in headers]]
    data += [[Paragraph(str(s),ST['cell']) for s in row] for row in rows]
    t=Table(data,colWidths=[CW*v for v in widths],hAlign='LEFT')
    t.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,0),NAVY),('VALIGN',(0,0),(-1,-1),'TOP'),
       ('LEFTPADDING',(0,0),(-1,-1),9),('RIGHTPADDING',(0,0),(-1,-1),9),
       ('TOPPADDING',(0,0),(-1,-1),8),('BOTTOMPADDING',(0,0),(-1,-1),8),
       ('ROWBACKGROUNDS',(0,1),(-1,-1),[white,PALE]),('LINEBELOW',(0,-1),(-1,-1),.5,LINE)]))
    _,hh=t.wrap(CW,H)
    if y+hh>H-46:raise ValueError('Table overflow')
    t.drawOn(C,M,H-y-hh)
    return y+hh


def pic(path,x,y,w,h,caption=None):
    path=Path(path)
    if not path.is_file():raise FileNotFoundError(path)
    iw,ih=Image.open(path).size;scale=min(w/iw,h/ih);dw,dh=iw*scale,ih*scale
    C.drawImage(str(path),x+(w-dw)/2,H-y-(h+dh)/2,width=dw,height=dh,mask='auto')
    if caption:para(x,y+h+4,caption,w,'small')
    AUDIT.append(dict(kind='image',page=C.getPageNumber(),file=str(path.relative_to(ROOT)),x=x,y=y,w=w,h=h))
    return (x+(w-dw)/2,y+(h-dh)/2,scale)


def kit(filename,y,height,labels):
    tx,ty,s=pic(CAD/(filename+'.png'),M,y,CW,height)
    notes=json.loads((CAD/'image-notes.json').read_text())['images'][filename]
    for item,label in zip(notes['panels'],labels):
        px,py=item['caption_px'];C.setFillColor(INK);C.setFont('Bold',8.1)
        C.drawCentredString(tx+px*s,H-(ty+py*s+7),label)


def callout(transform,target,label,pos):
    x,y,s=transform;px,py=target;lx,ly=pos
    arrow(lx,ly+14,x+px*s,y+py*s)
    tw=pdfmetrics.stringWidth(label,'Bold',9.2)+12
    box(lx-tw/2,ly-1,tw,16,white,r=3)
    C.setFillColor(TEAL);C.setFont('Bold',9.2);C.drawCentredString(lx,H-ly-10,label)


def badge(x,y,number):
    C.setFillColor(TEAL);C.circle(x+11,H-y-11,11,stroke=0,fill=1)
    C.setFillColor(white);C.setFont('Bold',10);C.drawCentredString(x+11,H-y-14.5,str(number))


